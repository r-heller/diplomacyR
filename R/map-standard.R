# Standard board loader --------------------------------------------------------

.map_cache <- new.env(parent = emptyenv())

#' Path to a board definition shipped with the package
#'
#' @param name Board name.
#' @param call Caller environment, for error reporting.
#' @return A file path.
#' @noRd
.map_file <- function(name = "standard", call = rlang::caller_env()) {
  path <- system.file(
    "extdata", paste0(name, "_map.json"),
    package = "diplomacyR", mustWork = FALSE
  )
  if (!nzchar(path)) {
    cli::cli_abort(
      "Board definition {.val {name}} is not installed with the package.",
      call = call
    )
  }
  path
}

#' Assemble the standard board from its JSON definition
#'
#' The JSON is generated by `data-raw/standard_map.R` from the classic judge
#' adjacency table. The result is cached for the session.
#'
#' @param call Caller environment, for error reporting.
#' @return A `dp_map` object, not yet validated.
#' @noRd
.load_standard_map <- function(call = rlang::caller_env()) {
  if (!is.null(.map_cache$standard)) return(.map_cache$standard)

  raw <- jsonlite::read_json(.map_file("standard", call = call),
                             simplifyVector = FALSE)

  provinces <- tibble::tibble(
    code = vapply(raw$provinces, function(p) p$code, character(1)),
    name = vapply(raw$provinces, function(p) p$name, character(1)),
    type = vapply(raw$provinces, function(p) p$type, character(1)),
    supply_centre = vapply(raw$provinces, function(p) isTRUE(p$supply_centre),
                           logical(1)),
    home_power = vapply(
      raw$provinces,
      function(p) if (is.null(p$home_power)) NA_character_ else p$home_power,
      character(1)
    ),
    x = vapply(raw$provinces, function(p) as.numeric(p$x), numeric(1)),
    y = vapply(raw$provinces, function(p) as.numeric(p$y), numeric(1))
  )

  coasts <- stats::setNames(
    lapply(raw$provinces, function(p) unlist(p$coasts) %||% character(0)),
    provinces$code
  )

  coast_xy <- tibble::tibble(
    loc = vapply(raw$coast_locations, function(p) p$loc, character(1)),
    x = vapply(raw$coast_locations, function(p) as.numeric(p$x), numeric(1)),
    y = vapply(raw$coast_locations, function(p) as.numeric(p$y), numeric(1))
  )

  as_chr_list <- function(x) lapply(x, function(e) unlist(e) %||% character(0))

  start_units <- tibble::tibble(
    power = vapply(raw$start_units, function(u) u$power, character(1)),
    type = vapply(raw$start_units, function(u) u$type, character(1)),
    loc = vapply(raw$start_units, function(u) u$loc, character(1))
  )

  base <- new_dp_map(
    name = raw$name,
    description = raw$description,
    powers = unlist(raw$powers),
    provinces = provinces,
    coasts = coasts,
    army_adj = as_chr_list(raw$army_adjacency),
    fleet_adj = as_chr_list(raw$fleet_adjacency),
    coast_xy = coast_xy,
    supply_centres = unlist(raw$supply_centres),
    home_centres = as_chr_list(raw$home_centres),
    start_units = start_units
  )
  # Precomputed sea/coast neighbourhoods: the convoy code walks these graphs
  # constantly and recomputing them dominates simulation time otherwise.
  base$adj_seas <- stats::setNames(
    lapply(c(provinces$code, coast_xy$loc),
           function(l) .adjacent_seas(base, l)),
    c(provinces$code, coast_xy$loc)
  )
  seas <- provinces$code[provinces$type == "sea"]
  base$adj_coasts <- stats::setNames(
    lapply(seas, function(s) .adjacent_coasts(base, s)), seas
  )
  .map_cache$standard <- base
  base
}
